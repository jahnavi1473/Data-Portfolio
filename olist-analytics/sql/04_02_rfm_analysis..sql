    SELECT
        c.customer_unique_id,
        COUNT(DISTINCT o.order_id) AS frequency

    FROM customers c

    JOIN orders o
        ON c.customer_id = o.customer_id

    JOIN order_payments op
        ON o.order_id = op.order_id

    GROUP BY
        c.customer_unique_id
),

segmented AS
(
    SELECT
        customer_unique_id,
        frequency,

        CASE
            WHEN frequency = 1 THEN '1 Order (One-Time Customer)'
            WHEN frequency = 2 THEN '2 Orders (Repeat Customer)'
