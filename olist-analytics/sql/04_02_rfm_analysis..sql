/* ============================================================
   OLIST E-COMMERCE ANALYTICS PROJECT
   FILE: 04_rfm_analysis.sql

   PURPOSE:
   Perform RFM (Recency, Frequency, Monetary) Analysis
   to understand customer behavior and build actionable
   customer segments.

   OBJECTIVES:

   1. Calculate Recency for every customer.
   2. Calculate Frequency for every customer.
   3. Calculate Monetary Value for every customer.
   4. Assign RFM Scores.
   5. Build Business Customer Segments.
   6. Identify Champions, Loyal Customers,
      Potential Loyalists, At Risk and Lost Customers.

============================================================ */

/* ============================================================
   RFM BASE TABLE
============================================================ */

WITH reference_date AS(
SELECT 
	MAX(order_purchase_timestamp::TIMESTAMP) AS analysis_date FROM orders
)
SELECT
    c.customer_unique_id,
    MAX(o.order_purchase_timestamp::TIMESTAMP) AS last_purchase_date,
    ( SELECT analysis_date FROM reference_date) AS analysis_date,
    ((SELECT analysis_date FROM reference_date) - 
	MAX(o.order_purchase_timestamp::TIMESTAMP)) AS recency,
    COUNT(DISTINCT o.order_id) AS frequency,
    ROUND(SUM(op.payment_value)::NUMERIC,2) AS monetary
FROM customers c
JOIN orders o
    ON c.customer_id = o.customer_id
JOIN order_payments op
    ON o.order_id = op.order_id
GROUP BY
    c.customer_unique_id;

/*
Results:

Rows Returned:
96,095

Each row represents one unique customer
with an associated Recency, Frequency,
and Monetary value.

Columns:

customer_unique_id
Unique identifier representing a customer.

last_purchase_date
Most recent purchase date of the customer.

analysis_date
Latest purchase date available in the dataset.
Used as the reference date for Recency calculations.

recency
Number of days between the customer's most
recent purchase and the analysis date.

frequency
Total number of unique orders placed
by the customer.

monetary
Total revenue generated by the customer.


Finding:

The RFM Base Table transforms transactional
order-level data into customer-level analytical
data.

This table serves as the foundation for all
subsequent RFM scoring and customer segmentation.

Using the maximum purchase date in the dataset
as the analysis date ensures that Recency is
measured consistently for every customer.

Business Implication:

Rather than analysing individual orders,
future analyses will evaluate customer
behavior based on purchasing recency,
purchase frequency, and total spending.
*/


/* ============================================================
   RECENCY ANALYSIS
============================================================ */

WITH reference_date AS (
SELECT
    MAX(order_purchase_timestamp::TIMESTAMP) AS analysis_date FROM orders),
rfm_base AS (
SELECT
	c.customer_unique_id,
    ((SELECT analysis_date FROM reference_date)::DATE -
	MAX(o.order_purchase_timestamp::DATE)) AS recency_days
FROM customers c
JOIN orders o
    ON c.customer_id = o.customer_id
JOIN order_payments op
    ON o.order_id = op.order_id
GROUP BY
    c.customer_unique_id
)
SELECT MIN(recency_days) AS minimum_recency,
ROUND(AVG(recency_days)::NUMERIC,2) AS average_recency,
ROUND(PERCENTILE_CONT(0.5) WITHIN GROUP (ORDER BY recency_days)::NUMERIC,2
) AS median_recency,
MAX(recency_days) AS maximum_recency
FROM rfm_base;

