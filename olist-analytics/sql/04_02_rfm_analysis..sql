/* ============================================================
   RFM SCORING
   Business Question:
   Assign Recency, Frequency, and Monetary scores to each customer.
============================================================ */

WITH reference_date AS (
SELECT MAX(order_purchase_timestamp::DATE) AS analysis_date FROM orders
),

rfm_base AS (
SELECT
	c.customer_unique_id,
	(
      (SELECT analysis_date FROM reference_date)
            -
      MAX(o.order_purchase_timestamp::DATE)
    ) AS recency_days,
	COUNT(DISTINCT o.order_id) AS frequency,
	ROUND(SUM(op.payment_value)::NUMERIC,2) AS monetary
FROM customers c
JOIN orders o
	ON c.customer_id = o.customer_id
JOIN order_payments op
	ON o.order_id = op.order_id
GROUP BY
	c.customer_unique_id
),

rfm_scores AS (
SELECT
	customer_unique_id,
	recency_days,
	frequency,
	monetary,

    --------------------------------------------------
        -- Recency Score
    --------------------------------------------------
	6 - NTILE(5) OVER
    (ORDER BY recency_days ASC) AS r_score,

    --------------------------------------------------
        -- Frequency Score
    --------------------------------------------------
	CASE
		WHEN frequency = 1 THEN 1
		WHEN frequency = 2 THEN 2
		WHEN frequency BETWEEN 3 AND 5 THEN 3
		WHEN frequency BETWEEN 6 AND 10 THEN 4
		ELSE 5
	END AS f_score,

    --------------------------------------------------
        -- Monetary Score
    --------------------------------------------------
	NTILE(5) OVER
    (ORDER BY monetary DESC ) AS m_score FROM rfm_base
)
SELECT * FROM rfm_scores
ORDER BY
    r_score DESC,
    f_score DESC,
    m_score DESC;


/* ============================================================
   SECTION 9: CUSTOMER SEGMENTATION

   Business Question:
   Segment customers into meaningful business groups using
   Recency, Frequency, and Monetary (RFM) analysis.

   Segment Logic:
   • Champions          : Recent, Repeat & High Spending Customers
   • At Risk            : Repeat Customers who have become inactive
   • Loyal Customers    : Repeat Customers
   • Promising          : Recent First-Time Buyers
   • Lost Customers     : Long Inactive One-Time Buyers
   • Hibernating        : Moderately Inactive One-Time Buyers
============================================================ */

WITH reference_date AS
(
    SELECT
        MAX(order_purchase_timestamp::DATE) AS analysis_date
    FROM orders
),

rfm_base AS
(
    SELECT

        c.customer_unique_id,

        (
            (SELECT analysis_date FROM reference_date)
            -
            MAX(o.order_purchase_timestamp::DATE)
        ) AS recency_days,

        COUNT(DISTINCT o.order_id) AS frequency,

        ROUND(
            SUM(op.payment_value)::NUMERIC,
            2
        ) AS monetary

    FROM customers c

    JOIN orders o
        ON c.customer_id = o.customer_id

    JOIN order_payments op
        ON o.order_id = op.order_id

    GROUP BY
        c.customer_unique_id
),

rfm_scores AS
(
    SELECT

        customer_unique_id,

        recency_days,

        frequency,

        monetary,

        ----------------------------------------------------
        -- Recency Score (Most Recent = 5)
        ----------------------------------------------------

        6 - NTILE(5) OVER
        (
            ORDER BY recency_days ASC
        ) AS r_score,

        ----------------------------------------------------
        -- Frequency Score
        ----------------------------------------------------

        CASE

            WHEN frequency = 1 THEN 1
            WHEN frequency = 2 THEN 2
            WHEN frequency BETWEEN 3 AND 5 THEN 3
            WHEN frequency BETWEEN 6 AND 10 THEN 4
            ELSE 5

        END AS f_score,

        ----------------------------------------------------
        -- Monetary Score (Highest Spending = 5)
        ----------------------------------------------------

        NTILE(5) OVER
        (
            ORDER BY monetary DESC
        ) AS m_score

    FROM rfm_base
)

SELECT

    customer_unique_id,

    recency_days,

    frequency,

    monetary,

    r_score,

    f_score,

    m_score,

    CASE

        ----------------------------------------------------
        -- Best Customers
        ----------------------------------------------------

        WHEN r_score >= 4
         AND frequency >= 2
         AND m_score >= 3
            THEN 'Champions'

        ----------------------------------------------------
        -- Previously Valuable Customers Becoming Inactive
        ----------------------------------------------------

        WHEN r_score <= 2
         AND frequency >= 2
            THEN 'At Risk'

        ----------------------------------------------------
        -- Active Repeat Customers
        ----------------------------------------------------

        WHEN frequency >= 2
            THEN 'Loyal Customers'

        ----------------------------------------------------
        -- Recent First-Time Customers
        ----------------------------------------------------

        WHEN r_score >= 4
         AND frequency = 1
            THEN 'Promising'

        ----------------------------------------------------
        -- Long Inactive One-Time Customers
        ----------------------------------------------------

        WHEN r_score = 1
         AND frequency = 1
            THEN 'Lost Customers'

        ----------------------------------------------------
        -- Remaining One-Time Customers
        ----------------------------------------------------

        ELSE 'Hibernating'

    END AS customer_segment

FROM rfm_scores

ORDER BY
    customer_segment,
    monetary DESC;


