        c.customer_unique_id
)

SELECT

    MIN(frequency) AS minimum_frequency,

    ROUND(AVG(frequency),2) AS average_frequency,

    PERCENTILE_CONT(0.5)
        WITHIN GROUP (ORDER BY frequency) AS median_frequency,

    MAX(frequency) AS maximum_frequency

FROM rfm_base;

