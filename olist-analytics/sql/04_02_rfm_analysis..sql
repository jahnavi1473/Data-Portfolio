/* ============================================================
   RECENCY DISTRIBUTION
   Business Question:
   How are customers distributed based on recency?
============================================================ */

WITH reference_date AS
(
    SELECT
        MAX(order_purchase_timestamp::DATE) AS analysis_date
    FROM orders
),

rfm_base AS
(
    SELECT

        c.customer_unique_id,

        (
            (
                SELECT analysis_date
                FROM reference_date
            )
            -
            MAX(o.order_purchase_timestamp::DATE)
        ) AS recency_days

    FROM customers c

    JOIN orders o
        ON c.customer_id = o.customer_id

    JOIN order_payments op
        ON o.order_id = op.order_id

    GROUP BY
        c.customer_unique_id
),

segmented AS
(
    SELECT

        customer_unique_id,
        recency_days,

        CASE

            WHEN recency_days BETWEEN 0 AND 30
                THEN '0-30 Days (Very Active)'

            WHEN recency_days BETWEEN 31 AND 90
                THEN '31-90 Days (Active)'

            WHEN recency_days BETWEEN 91 AND 180
                THEN '91-180 Days (Warm)'

            WHEN recency_days BETWEEN 181 AND 365
                THEN '181-365 Days (Inactive)'

            ELSE '365+ Days (Dormant)'

        END AS recency_segment

    FROM rfm_base
)

SELECT

    recency_segment,

    COUNT(*) AS customer_count,

    ROUND(
        COUNT(*) * 100.0 /
        SUM(COUNT(*)) OVER (),
        2
    ) AS percentage_of_customers

FROM segmented

GROUP BY
    recency_segment

ORDER BY
    MIN(recency_days);

